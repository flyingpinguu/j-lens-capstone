"""Small Colab A100 benchmark of the real Stage-1 readout pipeline.

Run from the repository root after installing the local jlens checkout. The
four selected requests cover two attack styles and both authorized families.
Secrets are regenerated by ``assign_single_token_secrets`` with the Qwen3-14B
tokenizer and validated in the rendered ``sys_strict`` system prompt.
"""

from copy import deepcopy
import json
from pathlib import Path
import statistics
import sys
import time


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from pipeline.pipeline_main import MODEL_CONFIGS, SETTINGS, load_stage, read_jsonl  # noqa: E402


SMOKE_CATEGORIES = (
    "direct_override",
    "storytelling",
    "admin_request",
    "password_correct",
)


def select_template_ids(injections):
    selected = []
    for category in SMOKE_CATEGORIES:
        match = next(
            (
                row["template_id"]
                for row in injections
                if row["category"] == category
                and row["label"] in {"attack", "authorized"}
            ),
            None,
        )
        if match is None:
            raise ValueError(f"No smoke row found for category {category!r}")
        selected.append(match)
    return selected


def main():
    injections = read_jsonl(
        ROOT / "data" / "evaluation" / "conversation_seeds.jsonl"
    )
    system_prompts = read_jsonl(
        ROOT / "data" / "evaluation" / "system_prompts_authz.jsonl"
    )

    settings = deepcopy(SETTINGS)
    settings.update(
        {
            "active_model": "qwen3-14b",
            "model": MODEL_CONFIGS["qwen3-14b"],
            "collection_mode": "single_turn",
            "include_labels": ["attack", "authorized"],
            "include_system_ids": ["sys_strict"],
            "template_ids": select_template_ids(injections),
            "max_prompts_per_strictness": None,
            "readout_positions": "last_n_prompt_plus_response",
            "readout_last_n": 16,
            "max_new_tokens": 64,
            "probe_enabled": True,
            "benchmark_timing": True,
            "output_dir": ROOT / "outputs" / "j-lens-benchmark",
        }
    )

    started = time.perf_counter()
    harness = load_stage("1_data_generation/run_harness.py")
    output_file = harness.run(settings, injections, system_prompts)
    wall_seconds = time.perf_counter() - started

    raw_lines = output_file.read_bytes().splitlines(keepends=True)
    records = [json.loads(line) for line in raw_lines if line.strip()]
    fresh = [row for row in records if "benchmark" in row]
    if not fresh:
        raise RuntimeError(
            "No benchmark rows found. Remove the existing smoke output and rerun."
        )

    line_bytes = [len(line) for line in raw_lines]
    full_run_count = sum(
        row["label"] in set(settings["include_labels"]) for row in injections
    ) * sum(
        row["system_id"] in set(settings["include_system_ids"])
        for row in system_prompts
    )
    report = {
        "model": settings["model"]["model_id"],
        "lens_file": settings["model"]["lens_file"],
        "system_id": "sys_strict",
        "secret_seed": settings["secret_seed"],
        "secret_min_token_id": settings["secret_min_token_id"],
        "wall_seconds_including_setup": wall_seconds,
        "records": [
            {
                "template_id": row["template_id"],
                "category": row["category"],
                "prompt_tokens": row["prompt_length"],
                "output_bytes": size,
                **row["benchmark"],
            }
            for row, size in zip(fresh, line_bytes)
        ],
        "output_file": str(output_file),
        "output_bytes": output_file.stat().st_size,
        "mean_output_bytes_per_run": statistics.mean(line_bytes),
        "full_filtered_run_count": full_run_count,
        "estimated_full_output_bytes": (
            statistics.mean(line_bytes) * full_run_count
        ),
    }
    report_file = output_file.with_suffix(".benchmark.json")
    report_file.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("\nBENCHMARK_JSON")
    print(json.dumps(report, indent=2))
    print("Saved benchmark report:", report_file)


if __name__ == "__main__":
    main()
